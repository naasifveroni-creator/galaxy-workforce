import asyncio
from datetime import date
from pathlib import Path
from pptx import Presentation
from core.registry import registry
from .base import BaseBot, TaskResult

OUT = Path(__file__).resolve().parent.parent / "output"


class ReportBot(BaseBot):
    bot_id, name, room, color = "report_bot", "ReportBot", "strategy_deck", "#f1c40f"

    async def work(self, **kwargs) -> TaskResult:
        tmp = OUT / "eod_DRAFT.pptx"
        # Aggregate whatever the other bots have produced (and you approved) so far.
        lines = [f"{bid}: {r['summary']}" for bid, rs in registry.outputs.items() if bid != self.bot_id for r in rs]

        def build():
            prs = Presentation()
            s = prs.slides.add_slide(prs.slide_layouts[0])
            s.shapes.title.text = f"EOD Report - {date.today():%d %b %Y}"
            s.placeholders[1].text = "Generated by the Galaxy Workforce"
            s = prs.slides.add_slide(prs.slide_layouts[1])
            s.shapes.title.text = "Today's Bot Activity"
            s.placeholders[1].text = "\n".join(lines) or "No approved outputs yet."
            prs.save(tmp)
        await asyncio.to_thread(build)
        return TaskResult(summary=f"EOD deck drafted ({len(lines)} items)", data={"draft": str(tmp), "preview": {"items": lines}})

    async def execute(self, result: TaskResult) -> None:
        Path(result.data["draft"]).replace(OUT / "eod_report.pptx")

    async def discard(self, result: TaskResult) -> None:
        Path(result.data["draft"]).unlink(missing_ok=True)
